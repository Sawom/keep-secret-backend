import { IsNotEmpty, IsObject, IsOptional, IsString } from 'class-validator';

/**
 * সিস্টেমের বিভিন্ন অ্যাকশন অটোমেটিক লগ করার জন্য DTO।
 */
export class CreateAuditLogDto {
    // অ্যাকশনের ধরন (যেমন: AUTH_LOGIN, NOTE_CREATE, NOTE_DELETE)
    @IsString()
    @IsNotEmpty()
    action: string;

    // ইউজার যে ডিভাইস বা ব্রাউজার থেকে রিকোয়েস্ট করেছে (ঐচ্ছিক)
    @IsString()
    @IsOptional()
    userAgent?: string;

    // ক্লায়েন্টের IP অ্যাড্রেস (ঐচ্ছিক)
    @IsString()
    @IsOptional()
    ipAddress?: string;

    // অ্যাকশন সম্পর্কিত অতিরিক্ত তথ্য (JSON/String ফরম্যাটে) (ঐচ্ছিক)
    @IsObject()
    @IsOptional()
    details?: Record<string, any>;
}


/**
    অডিট লগ (Audit Log) কী এবং এর কাজ কী?
    অডিট লগ হলো সিকিউরিটি অ্যাপ্লিকেশনের "ব্ল্যাক বক্স" বা সিসিটিভি ক্যামেরার মতো। এটি সিস্টেমে ঘটা প্রতিটা স্পর্শকাতর অ্যাকশনকে টাইমস্ট্যাম্পসহ রেকর্ড করে রাখে।
    KeepSecret-এর মতো জিরো-নলেজ অ্যাপে এর কাজ:
    সিকিউরিটি ট্র্যাকিং: ইউজার দেখতে পাবে তার অ্যাকাউন্টে কখন, কোন ডিভাইস (User-Agent) বা IP থেকে লগইন করা হয়েছে।
    সন্দেহজনক অ্যাক্টিভিটি শনাক্তকরণ: যদি কোনো অপরিচিত IP থেকে কোনো নোট ডিলিট বা এডিট হয়, ইউজার অডিট লগ দেখে সাথে সাথে ধরে ফেলতে পারবে।
    কমপ্লায়েন্স ও হিস্ট্রি: অ্যাকাউন্টের যাবতীয় অ্যাক্টিভিটির ১টি স্থায়ী সিকিউরিটি ট্রেইল তৈরি থাকা।
    অন্যান্য এপিআই (Create, Update, Delete) কেন নেই?
    এখানেই অডিট লগের বিশেষত্ব! অডিট লগে ইচ্ছে করে Update বা Delete এপিআই রাখা হয় না।
    কেন Delete/Update রাখা হয় না?
    অডিট লগ হলো Immutable Data (যা কখনো পরিবর্তন বা ডিলিট করা যায় না)। হ্যাকার যদি অ্যাকাউন্টে ঢুকে নোট ডিলিট করে, সে যেন সেই ডিলিট করার লগ ডাটাবেস থেকে মুছে প্রমাণ গায়েব না করতে পারে! তাই অডিট লগে কোনো PATCH বা DELETE এপিআই দেওয়া হয় না।
    Create এপিআই কেন সরাসরি কন্ট্রোলারে নেই
    ইউজার নিজে কখনো পোস্টম্যানে রিকোয়েস্ট পাঠিয়ে অডিট লগ বানাবে না। অডিট লগ তৈরি হবে অটোমেটিক্যালি। উদাহরণস্বরূপ: ইউজার যখন POST /notes হিট করবে, তখন NoteService-এর ভেতর থেকে ব্যাকগ্রাউন্ডে AuditLogService.log() কল হয়ে লগ তৈরি হয়ে যাবে।
 */